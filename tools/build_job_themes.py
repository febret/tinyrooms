"""Generate the per-job minigame themes (palette, pattern, edge, pip, corners).

Usage:
    python tools/build_job_themes.py

The output, ``mods/tinytown/activities/jobs/minigames/themes.js``, is committed;
rerun this script after adding or reordering jobs. Every job gets a unique
(pattern, edge) pair and a hue slot (6 degrees apart, golden-ratio ordered so neighbours differ).
"""

from __future__ import annotations

import colorsys
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from tools.build_jobs_assets import CONTENT_ROOT, _load_yaml

OUTPUT = REPO_ROOT / "mods" / "tinytown" / "activities" / "jobs" / "minigames" / "themes.js"
GROUP_PATTERNS = ["hatch", "stripes", "dots", "checker", "stars", "grid", "ledger", "bricks", "waves", "zigzag"]
EDGES = ["dashed", "solid", "double", "dotted", "bracket"]
PIPS = ["circle", "square", "diamond", "star", "hex", "heart", "triangle", "drop"]
CORNERS = ["brackets", "rivets", "tape", "stitch", "notch"]
MARKERS = ["line", "arrow", "diamond"]
FONTS = ["display", "body", "ui", "mono"]
GOLDEN = 0.6180339887


def hsl_hex(hue: float, sat: float, light: float) -> str:
    red, green, blue = colorsys.hls_to_rgb((hue % 360) / 360, light, sat)
    return f"#{round(red * 255):02x}{round(green * 255):02x}{round(blue * 255):02x}"


def hsl_rgba(hue: float, sat: float, light: float, alpha: float) -> str:
    red, green, blue = colorsys.hls_to_rgb((hue % 360) / 360, light, sat)
    return f"rgba({round(red * 255)}, {round(green * 255)}, {round(blue * 255)}, {alpha})"


def build() -> str:
    count = sum(
        len(_load_yaml(path))
        for path in CONTENT_ROOT.glob("*.yaml")
        if path.name != "complications.yaml"
    )
    order = sorted(range(count), key=lambda slot: (slot * GOLDEN) % 1)
    rank = {slot: place for place, slot in enumerate(order)}
    entries: list[str] = []
    seen: set[tuple[str, str]] = set()
    index = 0
    for group, path in enumerate(sorted(p for p in CONTENT_ROOT.glob("*.yaml") if p.name != "complications.yaml")):
        for position, (job_id, raw) in enumerate(_load_yaml(path).items()):
            hue = 30 + rank[index] * (300 / count)
            pattern = GROUP_PATTERNS[group % len(GROUP_PATTERNS)]
            edge = EDGES[(position + group) % len(EDGES)]
            if (pattern, edge) in seen:
                raise ValueError(f"Duplicate pattern/edge for {job_id}.")
            seen.add((pattern, edge))
            theme = {
                "good": hsl_hex(hue, 0.72, 0.62),
                "soft": hsl_rgba(hue, 0.7, 0.55, 0.3),
                "deep": hsl_hex(hue, 0.5, 0.16),
                "tint": hsl_rgba(hue, 0.45, 0.09, 0.62),
                "accent": str(raw.get("accent", "#d7795c")),
                "pattern": pattern,
                "edge": edge,
                "pip": PIPS[(index * 3 + group) % len(PIPS)],
                "corner": CORNERS[(index + group * 2) % len(CORNERS)],
                "marker": MARKERS[index % len(MARKERS)],
                "font": FONTS[(index // 2) % len(FONTS)],
            }
            body = ", ".join(f'{key}: "{value}"' for key, value in theme.items())
            entries.append(f'  "{job_id}": {{ {body} }},')
            index += 1
    header = (
        "// Generated by tools/build_job_themes.py. Do not edit by hand.\n"
        "// One theme per job: palette, target pattern/edge, HUD pip, frame corner, marker, and font.\n\n"
    )
    return header + "export const THEMES = {\n" + "\n".join(entries) + "\n};\n"


def main() -> int:
    OUTPUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
